def main():
    client = Client()

    # Находим dataset
    dataset = client.read_dataset(dataset_name=DATASET_NAME)

    print(f"Dataset found: {dataset.name}")
    print(f"Dataset ID: {dataset.id}")

    # Получаем существующие examples
    existing_examples = list(
        client.list_examples(dataset_id=dataset.id)
    )

    existing_by_case_id = {
        example.inputs.get("case_id"): example
        for example in existing_examples
        if example.inputs and example.inputs.get("case_id")
    }

    print(f"Existing examples: {len(existing_examples)}")

    created_count = 0
    updated_count = 0

    for case in EVAL_CASES:
        case_id = case["inputs"]["case_id"]

        if case_id in existing_by_case_id:
            # Example уже существует:
            # записываем / исправляем его Reference Output
            example = existing_by_case_id[case_id]

            client.update_example(
                example_id=example.id,
                inputs=case["inputs"],
                outputs=case["outputs"],
            )

            updated_count += 1
            print(f"Updated: {case_id}")

        else:
            # Если example отсутствует — создаем
            client.create_example(
                dataset_id=dataset.id,
                inputs=case["inputs"],
                outputs=case["outputs"],
            )

            created_count += 1
            print(f"Created: {case_id}")

    print()
    print(f"Created examples: {created_count}")
    print(f"Updated examples: {updated_count}")

    # Контрольная проверка
    final_examples = list(
        client.list_examples(dataset_id=dataset.id)
    )

    print(f"Total examples in dataset: {len(final_examples)}")

    examples_with_outputs = sum(
        1
        for example in final_examples
        if example.outputs
    )

    print(f"Examples with reference outputs: {examples_with_outputs}")

    if len(final_examples) == 10 and examples_with_outputs == 10:
        print("Dataset upload: OK")
    else:
        print(
            "WARNING: expected 10 examples with reference outputs."
        )


if __name__ == "__main__":
    main()